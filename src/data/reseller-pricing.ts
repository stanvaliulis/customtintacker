// Site SKU -> sheet Product ID, where the two differ.
const SKU_ALIASES: Record<string, string> = {
  TSASH22000090: 'TSAPN22000090', // 22" x 9" — sheet lists it as a Pennant Tacker
};

export function getResellerPrices(sku?: string | null): number[] | null {
  if (!sku) return null;
  return resellerPricing[sku] ?? resellerPricing[SKU_ALIASES[sku] ?? ''] ?? null;
}

/** Attach sheet reseller prices to each pricing tier (by minimum quantity). */
export function applyResellerPricing<T extends Pick<Product, 'sku' | 'pricingTiers'>>(product: T): T {
  const prices = getResellerPrices(product.sku);
  if (!prices) return product;
  for (const tier of product.pricingTiers) {
    const idx = RESELLER_BREAKS.indexOf(tier.minQuantity as (typeof RESELLER_BREAKS)[number]);
    if (idx >= 0 && prices[idx]) tier.resellerPrice = prices[idx];
  }
  return product;
}
